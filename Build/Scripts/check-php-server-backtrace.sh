#!/usr/bin/env bash
#
# Checks the backtrace that "Report PHP server status" in e2e.yml prints for a
# php core file. gdb prints frame #0 once when it loads the core and again as
# the first line of `bt`; a filter on `^#[0-9]+ ` over the whole output kept
# both, so the report showed #0 twice.
#
# The check runs the step's own bash with a stand-in gdb that behaves like
# gdb 15.1 on ubuntu-24.04: it prints the load-time output (captured from a
# real core, including the first #0 line), then runs each `-ex` command in
# order. The /tmp paths of the step are moved into a scratch directory, and
# sudo fails, so no kernel log is read and nothing is installed.
#
# Usage: check-php-server-backtrace.sh [path/to/e2e.yml]

set -uo pipefail

WORKFLOW="${1:-.github/workflows/e2e.yml}"
[[ -f "${WORKFLOW}" ]] || { printf 'not found: %s\n' "${WORKFLOW}" >&2; exit 2; }

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
FAILED=0

fail() { printf '  FAIL: %s\n' "${1}" >&2; FAILED=1; return 0; }
pass() { printf '  ok: %s\n' "${1}"; return 0; }

printf 'PHP server backtrace (%s)\n' "${WORKFLOW}"

body="${TMP}/step.sh"
yq -o json '.jobs' "${WORKFLOW}" \
    | jq -r '.[].steps[]? | select(.name == "Report PHP server status") | .run' > "${body}"
if [[ ! -s "${body}" ]]; then
    fail 'no step "Report PHP server status" with a run block'
    exit "${FAILED}"
fi

# Output of `gdb -batch -ex bt php <core>` (GNU gdb 15.1, ubuntu 24.04), split
# where the load-time output ends and the output of `bt` begins.
cat > "${TMP}/gdb-load.txt" <<'GDB'
[New LWP 6872]

warning: Section `.reg-xstate/6872' in core file too small.
[Thread debugging using libthread_db enabled]
Using host libthread_db library "/lib/x86_64-linux-gnu/libthread_db.so.1".
Core was generated by `php'.

warning: Section `.reg-xstate/6872' in core file too small.
#0  0x0000778f3a8dab7a in __GI___clock_nanosleep (clock_id=clock_id@entry=0, flags=flags@entry=0, req=req@entry=0x7ffd4cdd4700, rem=rem@entry=0x7ffd4cdd4700) at ../sysdeps/unix/sysv/linux/clock_nanosleep.c:78

warning: 78	../sysdeps/unix/sysv/linux/clock_nanosleep.c: No such file or directory
GDB
cat > "${TMP}/gdb-bt.txt" <<'GDB'
#0  0x0000778f3a8dab7a in __GI___clock_nanosleep (clock_id=clock_id@entry=0, flags=flags@entry=0, req=req@entry=0x7ffd4cdd4700, rem=rem@entry=0x7ffd4cdd4700) at ../sysdeps/unix/sysv/linux/clock_nanosleep.c:78
#1  0x0000778f3a8e7b27 in __GI___nanosleep (req=req@entry=0x7ffd4cdd4700, rem=rem@entry=0x7ffd4cdd4700) at ../sysdeps/unix/sysv/linux/nanosleep.c:25
#2  0x0000778f3a8fcd93 in __sleep (seconds=0) at ../sysdeps/posix/sleep.c:55
#3  0x00005701d8a9cc69 in ?? ()
#4  0x00005701d8bf2142 in execute_ex ()
#5  0x00005701d8bf8b61 in zend_execute ()
#6  0x00005701d8b70621 in zend_eval_stringl ()
#7  0x00005701d8b70825 in zend_eval_stringl_ex ()
#8  0x00005701d8c71fe8 in ?? ()
#9  0x00005701d89977e1 in ?? ()
#10 0x0000778f3a8181ca in __libc_start_call_main (main=main@entry=0x5701d8997490, argc=argc@entry=3, argv=argv@entry=0x7ffd4cdd5f88) at ../sysdeps/nptl/libc_start_call_main.h:58
#11 0x0000778f3a81828b in __libc_start_main_impl (main=0x5701d8997490, argc=3, argv=0x7ffd4cdd5f88, init=<optimized out>, fini=<optimized out>, rtld_fini=<optimized out>, stack_end=0x7ffd4cdd5f78) at ../csu/libc-start.c:360
#12 0x00005701d8998965 in _start ()
GDB

mkdir -p "${TMP}/bin" "${TMP}/tmp/php-cores"
# gdb loads the program and the core first, then runs each -ex in order.
cat > "${TMP}/bin/gdb" <<GDB
#!/usr/bin/env bash
cat "${TMP}/gdb-load.txt"
while (( \$# > 0 )); do
    if [[ "\$1" == -ex ]]; then
        case "\$2" in
            'echo '*) printf '%b' "\${2#echo }" ;;
            bt) cat "${TMP}/gdb-bt.txt" ;;
        esac
        shift
    fi
    shift
done
GDB
printf '#!/bin/sh\nexit 0\n' > "${TMP}/bin/php"
printf '#!/bin/sh\nexit 1\n' > "${TMP}/bin/sudo"
chmod +x "${TMP}/bin/gdb" "${TMP}/bin/php" "${TMP}/bin/sudo"

# A server that answered once and is gone, with one core file of its own.
echo 999999999 > "${TMP}/tmp/php-server.pid"
touch "${TMP}/tmp/php-server.up" "${TMP}/tmp/php-server.log" "${TMP}/tmp/php-cores/core.php.4242.11"

script="${TMP}/run.sh"
sed "s#/tmp/#${TMP}/tmp/#g" "${body}" > "${script}"
out="$(PATH="${TMP}/bin:${PATH}" PHP_CLI_SERVER_WORKERS=1 bash -e "${script}" 2>&1)"
status=$?

frames="$(awk '/^::group::Backtrace from / { on = 1; next } /^::endgroup::/ { on = 0 } on' <<< "${out}")"
count_all="$(grep -cE '^#[0-9]+ ' <<< "${frames}")"
count_0="$(grep -cE '^#0 ' <<< "${frames}")"

if [[ "${status}" -ne 0 ]]; then
    fail "the step exited ${status}; it must never change the job result"
fi
if [[ "${count_0}" -eq 1 ]]; then
    pass 'frame #0 appears once'
else
    fail "frame #0 appears ${count_0} times"
fi
if [[ "${count_all}" -eq 13 ]]; then
    pass 'all 13 frames of bt are printed'
else
    fail "${count_all} frame lines printed, expected the 13 of bt"
fi
if [[ "${FAILED}" -ne 0 ]]; then
    printf '%s\n' "${out}" >&2
fi

exit "${FAILED}"
